// Docker's build context is website/. Keep this generated runtime copy in sync
// with services/mobile-relay, just like the existing Plugin Guide snapshot.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../../services/mobile-relay/', import.meta.url);
const destination = new URL('../relay/mobile/', import.meta.url);
const files = ['server.mjs', 'protocol.mjs', 'machine-routes.mjs'];
const banner = '// Generated by scripts/sync-mobile-relay.mjs. Edit services/mobile-relay instead.\n';
mkdirSync(destination, { recursive: true });
for (const file of files) {
  const target = new URL(file, destination);
  if (existsSync(new URL(file, source))) writeFileSync(target, banner + readFileSync(new URL(file, source), 'utf8'));
  else if (!existsSync(target)) throw new Error(`Missing mobile relay snapshot: ${fileURLToPath(target)}`);
}

// Dependency-free machine bootstrap is served by Connect before host credentials exist.
const bootstrap = new URL('../../services/machine-bootstrap/install.mjs', import.meta.url);
const bootstrapTarget = new URL('../connect/host-installer.mjs', import.meta.url);
if (existsSync(bootstrap)) writeFileSync(bootstrapTarget, readFileSync(bootstrap, 'utf8'));
else if (!existsSync(bootstrapTarget)) throw new Error('Missing machine bootstrap snapshot');
